#!/usr/bin/env python3
"""Regenerate pinned Unicode General_Category=Me ranges, without network I/O."""

import argparse
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
VERSION = "18.0.0"
SOURCE = ROOT / "data" / "unicode" / VERSION / "DerivedGeneralCategory.txt"
LICENSE = ROOT / "data" / "unicode" / "LICENSE.txt"
OUTPUT = ROOT / "src" / "unicode" / "enclosing_mark_data.rs"
SOURCE_SHA256 = "d6b151d2d40ee9b1876d26f417980f45ffae47b6055ccf7203cb31f07a030f94"
LICENSE_SHA256 = "e7a93b009565cfce55919a381437ac4db883e9da2126fa28b91d12732bc53d96"


def generate():
    raw = SOURCE.read_bytes()
    if len(raw) != 282143 or hashlib.sha256(raw).hexdigest() != SOURCE_SHA256:
        raise ValueError("Pinned Unicode source size or SHA-256 does not match")
    if hashlib.sha256(LICENSE.read_bytes()).hexdigest() != LICENSE_SHA256:
        raise ValueError("Pinned Unicode license SHA-256 does not match")
    source = raw.decode("utf-8")
    if not source.startswith(f"# DerivedGeneralCategory-{VERSION}.txt\n"):
        raise ValueError("Unexpected Unicode version header")

    ranges = []
    for line in source.splitlines():
        fields = line.split("#", 1)[0].strip()
        if not fields:
            continue
        codepoints, category = (part.strip() for part in fields.split(";"))
        if category != "Me":
            continue
        first, _, last = codepoints.partition("..")
        start, end = int(first, 16), int(last or first, 16)
        if not 0 <= start <= end <= 0x10FFFF:
            raise ValueError(f"Invalid enclosing-mark range: {line}")
        if start <= 0xDFFF and end >= 0xD800:
            raise ValueError("Unexpected enclosing-mark surrogate range")
        if ranges and start <= ranges[-1][1]:
            raise ValueError("Unsorted or overlapping enclosing-mark ranges")
        if ranges and start == ranges[-1][1] + 1:
            ranges[-1] = (ranges[-1][0], end)
        else:
            ranges.append((start, end))
    count = sum(end - start + 1 for start, end in ranges)
    if len(ranges) != 5 or count != 13:
        raise ValueError("Unexpected enclosing-mark range or scalar count")

    lines = [
        "// @generated by tools/generate_enclosing_marks.py; do not edit.",
        f"// Unicode {VERSION}: https://www.unicode.org/Public/{VERSION}/ucd/extracted/DerivedGeneralCategory.txt",
        f"// Source SHA-256: {SOURCE_SHA256}",
        "// Copyright (c) 2026 Unicode, Inc. SPDX-License-Identifier: Unicode-3.0",
        "// License: data/unicode/LICENSE.txt; provenance: data/unicode/README.md.",
        "// Sorted, disjoint, inclusive General_Category=Me ranges (13 scalars).",
        "",
        "#[rustfmt::skip]",
        "pub(super) const RANGES: &[(u32, u32)] = &[",
    ]
    lines.extend(f"    (0x{start:04X}, 0x{end:04X})," for start, end in ranges)
    lines.extend(["];", ""])
    return "\n".join(lines).encode("utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if regeneration would change the table")
    args = parser.parse_args()
    generated = generate()
    if args.check:
        if OUTPUT.read_bytes() != generated:
            parser.exit(1, "Generated table is out of date; run this script without --check.\n")
        print("Unicode 18.0.0 source/license hashes and enclosing-mark table verified (5 ranges, 13 scalars).")
    else:
        OUTPUT.write_bytes(generated)
        print(f"Wrote {OUTPUT.relative_to(ROOT)} (5 ranges, 13 scalars).")


if __name__ == "__main__":
    main()
