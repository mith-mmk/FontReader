#!/usr/bin/env python3
"""Generate pinned Unicode joining types; --check verifies reproducibility."""
from pathlib import Path
import hashlib
import sys

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "data/unicode/17.0.0/DerivedJoiningType.txt"
SHA256 = "f39ebe974825d6736aee15582250307aa532b2cfab3caf3f86bd23fddc9c5c4d"
assert hashlib.sha256(SOURCE.read_bytes()).hexdigest() == SHA256
ranges = []
for line in SOURCE.read_text().splitlines():
    data = line.split("#")[0].strip()
    if not data:
        continue
    points, value = map(str.strip, data.split(";"))
    bounds = points.split("..")
    start, end = int(bounds[0], 16), int(bounds[-1], 16)
    assert value in "CDRLT" and start <= end <= 0x10FFFF
    ranges.append((start, end, value))
ranges.sort()
assert all(a[1] < b[0] for a, b in zip(ranges, ranges[1:]))
text = "// @generated by tools/generate_joining_types.py; do not edit.\n"
text += "// Unicode 17.0.0 DerivedJoiningType.txt; see data/unicode/README.md.\n"
text += "// Copyright (c) 2025 Unicode, Inc. SPDX-License-Identifier: Unicode-3.0\n"
text += "#[rustfmt::skip]\npub(super) const RANGES: &[(u32, u32, u8)] = &[\n"
text += "".join(f"    (0x{a:04X}, 0x{b:04X}, b'{v}'),\n" for a, b, v in ranges)
text += "];\n"
out = ROOT / "src/unicode/joining_type_data.rs"
if "--check" in sys.argv:
    assert out.read_text() == text, "joining type data is stale"
else:
    out.write_text(text)
