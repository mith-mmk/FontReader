#!/usr/bin/env python3
"""Generate the bounded kana Unicode 17 canonical data, offline."""
import argparse
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "data/unicode/17.0.0/UnicodeData.txt"
OUTPUT = ROOT / "src/unicode/kana_composition_data.rs"
SOURCE_SHA256 = "2e1efc1dcb59c575eedf5ccae60f95229f706ee6d031835247d843c11d96470c"
LICENSE_SHA256 = "e7a93b009565cfce55919a381437ac4db883e9da2126fa28b91d12732bc53d96"


def generate():
    raw = SOURCE.read_bytes()
    assert len(raw) == 2198209
    assert hashlib.sha256(raw).hexdigest() == SOURCE_SHA256
    assert hashlib.sha256((ROOT / "data/unicode/LICENSE.txt").read_bytes()).hexdigest() == LICENSE_SHA256
    rows = [line.split(";") for line in raw.decode("utf-8").splitlines()]
    by_cp = {int(row[0], 16): row for row in rows}
    exclusions_raw = (ROOT / "data/unicode/17.0.0/CompositionExclusions.txt").read_bytes()
    assert hashlib.sha256(exclusions_raw).hexdigest() == "2f239196ef3b5b61db5cc476e9bd80f534d15aa1b74e1be1dea5d042a344c85f"
    exclusions = {int(line.split("#")[0].strip(), 16) for line in exclusions_raw.decode().splitlines()
                  if line.split("#")[0].strip()}
    rows = [row for row in rows if 0x3040 <= int(row[0], 16) <= 0x30FF]
    decomp = {int(row[0], 16): [int(cp, 16) for cp in row[5].split()]
              for row in rows if row[5] and not row[5].startswith("<")}
    assert len(decomp) == 58
    assert all(len(parts) == 2 and parts[1] in (0x3099, 0x309A)
               and 0x3040 <= parts[0] <= 0x30FF for parts in decomp.values())
    # UAX15 rev57: exclude explicit exclusions, singleton/nonstarter targets,
    # and recursive decompositions. All admitted bases are canonical starters.
    assert all(cp not in exclusions and int(by_cp[cp][3]) == 0
               and int(by_cp[parts[0]][3]) == 0 and not by_cp[parts[0]][5]
               for cp, parts in decomp.items())
    esc = lambda cp: "'\\u{%04x}'" % cp
    lines = ["// Generated by tools/generate_kana_composition.py. Do not edit.",
             "// Unicode 17.0.0; copyright (c) 2025 Unicode, Inc. Unicode-3.0.",
             "// See data/unicode/README.md for the pinned original and checksums.", "",
             "pub(crate) const DECOMPOSITIONS: &[(char, [char; 2])] = &["]
    lines += [f"    ({esc(cp)}, [{esc(parts[0])}, {esc(parts[1])}])," for cp, parts in decomp.items()]
    return "\n".join(lines + ["];", ""])


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    result = generate()
    if args.check:
        assert OUTPUT.read_text() == result, "Generated kana data differs"
    else:
        OUTPUT.write_text(result)
    print("Unicode 17 kana canonical data and license verified")
