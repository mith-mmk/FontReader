#!/usr/bin/env python3
"""Generate the bounded ASCII-base Latin Unicode 17 canonical data, offline."""
import argparse
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "data/unicode/17.0.0/UnicodeData.txt"
OUTPUT = ROOT / "src/unicode/latin_composition_data.rs"
SOURCE_SHA256 = "2e1efc1dcb59c575eedf5ccae60f95229f706ee6d031835247d843c11d96470c"
LICENSE_SHA256 = "e7a93b009565cfce55919a381437ac4db883e9da2126fa28b91d12732bc53d96"


def generate():
    raw = SOURCE.read_bytes()
    assert len(raw) == 2198209
    assert hashlib.sha256(raw).hexdigest() == SOURCE_SHA256
    assert hashlib.sha256((ROOT / "data/unicode/LICENSE.txt").read_bytes()).hexdigest() == LICENSE_SHA256
    rows = [line.split(";") for line in raw.decode("utf-8").splitlines()]
    by_cp = {int(row[0], 16): row for row in rows}
    exclusions_raw = (ROOT / "data/unicode/17.0.0/CompositionExclusions.txt").read_bytes()
    assert hashlib.sha256(exclusions_raw).hexdigest() == "2f239196ef3b5b61db5cc476e9bd80f534d15aa1b74e1be1dea5d042a344c85f"
    exclusions = {int(line.split("#")[0].strip(), 16) for line in exclusions_raw.decode().splitlines()
                  if line.split("#")[0].strip()}
    def expand(cp):
        field = by_cp[cp][5]
        if not field or field.startswith('<'):
            return [cp]
        return [x for part in field.split() for x in expand(int(part,16))]
    decomp = {}
    for cp, row in by_cp.items():
        if cp in exclusions or int(row[3]) != 0 or not row[1].startswith('LATIN '):
            continue
        parts = expand(cp)
        if (len(parts) in (2,3) and (65 <= parts[0] <= 90 or 97 <= parts[0] <= 122)
            and all(0x300 <= x <= 0x36f and int(by_cp[x][3]) > 0 for x in parts[1:])
            and all(int(by_cp[a][3]) <= int(by_cp[b][3]) for a,b in zip(parts[1:],parts[2:]))):
            decomp[cp] = parts
    esc = lambda cp: "'\\u{%04x}'" % cp
    lines = ["// Generated by tools/generate_latin_composition.py. Do not edit.",
             "// Unicode 17.0.0; copyright (c) 2025 Unicode, Inc. Unicode-3.0.",
             "// See data/unicode/README.md for the pinned original and checksums.", "",
             "pub(crate) const DECOMPOSITIONS: &[(char, &[char])] = &["]
    lines += [f"    ({esc(cp)}, &[{', '.join(map(esc, parts))}])," for cp, parts in decomp.items()]
    lines += ["];", "", "pub(crate) const MARK_CLASSES: &[(char, u8)] = &["]
    lines += [f"    ({esc(cp)}, {row[3]})," for cp,row in by_cp.items()
              if 0x300 <= cp <= 0x36f and int(row[3]) > 0]
    return "\n".join(lines + ["];", ""])


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    result = generate()
    if args.check:
        assert OUTPUT.read_text() == result, "Generated latin data differs"
    else:
        OUTPUT.write_text(result)
    print("Unicode 17 latin canonical data and license verified")
