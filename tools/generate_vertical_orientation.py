#!/usr/bin/env python3
"""Regenerate the pinned Unicode Vertical_Orientation table, without network I/O."""

import argparse
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
VERSION = "18.0.0"
SOURCE = ROOT / "data" / "unicode" / VERSION / "VerticalOrientation.txt"
LICENSE = ROOT / "data" / "unicode" / "LICENSE.txt"
OUTPUT = ROOT / "src" / "unicode" / "vertical_orientation_data.rs"
SOURCE_SHA256 = "0803e09669d7aa7137de678e55b848bd418c6632694fa1b05f0b40941103c748"
LICENSE_SHA256 = "e7a93b009565cfce55919a381437ac4db883e9da2126fa28b91d12732bc53d96"
VARIANTS = {
    "U": "Upright",
    "R": "Rotated",
    "Tu": "TransformWithUprightFallback",
    "Tr": "TransformWithRotatedFallback",
}


def generate():
    raw = SOURCE.read_bytes()
    if hashlib.sha256(raw).hexdigest() != SOURCE_SHA256:
        raise ValueError("Pinned Unicode source SHA-256 does not match")
    if hashlib.sha256(LICENSE.read_bytes()).hexdigest() != LICENSE_SHA256:
        raise ValueError("Pinned Unicode license SHA-256 does not match")
    source = raw.decode("utf-8")
    if not source.startswith(f"# VerticalOrientation-{VERSION}.txt\n"):
        raise ValueError("Unexpected Unicode version header")
    missing = [line for line in source.splitlines() if "@missing:" in line]
    if missing != ["# @missing: 0000..10FFFF; R"]:
        raise ValueError("Expected a single whole-code-space default of R")

    ranges = []
    end_before = -1
    row_count = 0
    for line in source.splitlines():
        fields = line.split("#", 1)[0].strip()
        if not fields:
            continue
        codepoints, value = (part.strip() for part in fields.split(";"))
        first, _, last = codepoints.partition("..")
        start, end = int(first, 16), int(last or first, 16)
        if value not in VARIANTS or not 0 <= start <= end <= 0x10FFFF:
            raise ValueError(f"Invalid property row: {line}")
        if start <= end_before:
            raise ValueError("Unsorted or overlapping source ranges")
        end_before = end
        row_count += 1
        if value == "R":
            continue
        # Rust char excludes surrogates. Refuse a future source that requires
        # storing non-default surrogate values instead of silently discarding it.
        if start <= 0xDFFF and end >= 0xD800:
            raise ValueError("Unexpected non-default surrogate range")
        if ranges and ranges[-1][1] + 1 == start and ranges[-1][2] == value:
            ranges[-1] = (ranges[-1][0], end, value)
        else:
            ranges.append((start, end, value))
    if row_count != 2499 or len(ranges) != 192:
        raise ValueError("Unexpected source-row or merged-range count")

    lines = [
        "// @generated by tools/generate_vertical_orientation.py; do not edit.",
        f"// Unicode {VERSION}: https://www.unicode.org/Public/{VERSION}/ucd/VerticalOrientation.txt",
        f"// Source SHA-256: {SOURCE_SHA256}",
        "// Copyright (c) 2026 Unicode, Inc. SPDX-License-Identifier: Unicode-3.0",
        "// License: data/unicode/LICENSE.txt; provenance: data/unicode/README.md.",
        "// Sorted, disjoint, inclusive non-R ranges. Every omitted scalar is R.",
        "",
        "use super::VerticalOrientation::{self, *};",
        "",
        f'pub(super) const UNICODE_VERSION: &str = "{VERSION}";',
        "",
        "#[rustfmt::skip]",
        "pub(super) const RANGES: &[(u32, u32, VerticalOrientation)] = &[",
    ]
    lines.extend(
        f"    (0x{start:04X}, 0x{end:04X}, {VARIANTS[value]}),"
        for start, end, value in ranges
    )
    lines.extend(["];", ""])
    return "\n".join(lines).encode("utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if regeneration would change the table")
    args = parser.parse_args()
    generated = generate()
    if args.check:
        if OUTPUT.read_bytes() != generated:
            parser.exit(1, "Generated table is out of date; run this script without --check.\n")
        print("Unicode 18.0.0 source/license hashes and generated table verified (192 ranges).")
    else:
        OUTPUT.write_bytes(generated)
        print(f"Wrote {OUTPUT.relative_to(ROOT)} (192 ranges).")


if __name__ == "__main__":
    main()
