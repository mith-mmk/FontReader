#!/usr/bin/env python3
"""Generate the bounded Tibetan Unicode 17 canonical data, offline."""
import argparse
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "data/unicode/17.0.0/UnicodeData.txt"
OUTPUT = ROOT / "src/unicode/tibetan_normalization_data.rs"
SOURCE_SHA256 = "2e1efc1dcb59c575eedf5ccae60f95229f706ee6d031835247d843c11d96470c"
LICENSE_SHA256 = "e7a93b009565cfce55919a381437ac4db883e9da2126fa28b91d12732bc53d96"


def generate():
    raw = SOURCE.read_bytes()
    assert len(raw) == 2198209
    assert hashlib.sha256(raw).hexdigest() == SOURCE_SHA256
    assert hashlib.sha256((ROOT / "data/unicode/LICENSE.txt").read_bytes()).hexdigest() == LICENSE_SHA256
    rows = [line.split(";") for line in raw.decode("utf-8").splitlines()]
    rows = [row for row in rows if 0xF00 <= int(row[0], 16) <= 0xFFF]
    assert len(rows) == 211
    decomp = {int(row[0], 16): [int(cp, 16) for cp in row[5].split()]
              for row in rows if row[5] and not row[5].startswith("<")}
    ccc = {int(row[0], 16): int(row[3]) for row in rows if int(row[3])}
    assert len(decomp) == 17 and len(ccc) == 19
    assert all(len(parts) == 2 and all(cp not in decomp for cp in parts) for parts in decomp.values())
    assert 0xF77 not in decomp and 0xF79 not in decomp
    esc = lambda cp: "'\\u{%04x}'" % cp
    lines = ["// Generated by tools/generate_tibetan_normalization.py. Do not edit.",
             "// Unicode 17.0.0; copyright (c) 2025 Unicode, Inc. Unicode-3.0.",
             "// See data/unicode/README.md for the pinned original and checksums.", "",
             "pub(super) const DECOMPOSITIONS: &[(char, [char; 2])] = &["]
    lines += [f"    ({esc(cp)}, [{esc(parts[0])}, {esc(parts[1])}])," for cp, parts in decomp.items()]
    lines += ["];", "", "pub(super) const COMBINING_CLASSES: &[(char, u8)] = &["]
    lines += [f"    ({esc(cp)}, {value})," for cp, value in ccc.items()]
    return "\n".join(lines + ["];", ""])


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    result = generate()
    if args.check:
        assert OUTPUT.read_text() == result, "Generated Tibetan data differs"
    else:
        OUTPUT.write_text(result)
    print("Unicode 17 Tibetan canonical data and license verified")
